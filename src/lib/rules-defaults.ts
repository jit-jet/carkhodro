export function toRulesContentVM(row: {
  updatedLabel: string | null;
  intro: string | null;
  body: string;
} | null): RulesContentVM {
  if (!row || !row.body.trim()) {
    return { ...DEFAULT_RULES_CONTENT };
  }
  return {
    updatedLabel: row.updatedLabel?.trim() || DEFAULT_RULES_CONTENT.updatedLabel,
    intro: row.intro?.trim() || DEFAULT_RULES_CONTENT.intro,
    body: row.body,
  };
}
